// Generates src/theme/tokens.generated.css from src/theme/tokens.ts (run with Node's built-in TS stripping).
import { writeFileSync } from 'node:fs';
import { tokens } from '../src/theme/tokens.ts';

const lines = ['/* GENERATED by scripts/gen-tokens.mjs — edit src/theme/tokens.ts instead. */', '@theme static {'];
for (const [k, v] of Object.entries(tokens.color)) lines.push(`  --color-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.shadow)) lines.push(`  --shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.radius)) lines.push(`  --radius-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.font)) lines.push(`  --font-${k}: ${v};`);
lines.push('}', '');
writeFileSync(new URL('../src/theme/tokens.generated.css', import.meta.url), lines.join('\n'));
